/**
 * Build the replay scene images once (deliberate local command; spends credits):
 *   npx tsx scripts/build-replay-assets.ts
 * Generates one reviewed image per replay era beat from the fixture's atlas
 * markers through the same HistoricalImageAgent path as live episodes, writes
 * them to public/assets/replay/ with a manifest, and regenerates
 * src/contracts/replayAssets.ts. Fixture scenes only; no personal data.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPLAY } from "../src/contracts/fixtures.ts";
import { illustrateBriefs, sceneBriefs } from "../src/server/images.ts";

const OUT_DIR = join(process.cwd(), "public", "assets", "replay");
const CONTRACT = join(process.cwd(), "src", "contracts", "replayAssets.ts");

const briefs = sceneBriefs(REPLAY.plan).map((brief) => ({
  ...brief,
  purpose: `Contextual illustration for the ${brief.era} chapter of the saved demonstration episode.`,
}));
if (briefs.length === 0) throw new Error("replay plan has no atlas-backed era beats");
const hook = REPLAY.plan.beats.find((b) => b.kind === "hook");
mkdirSync(OUT_DIR, { recursive: true });
const result = await illustrateBriefs({ dir: OUT_DIR, urlBase: "/assets/replay", mode: "replay" }, briefs, hook?.id ?? null, 0);

writeFileSync(join(OUT_DIR, "manifest.json"), JSON.stringify({ builtAt: new Date().toISOString(), scenes: result.outcomes.map((o) => o.manifest), costUsd: result.costUsd }, null, 1));
const body = [
  "/** Replay scene images: generated by scripts/build-replay-assets.ts, audited, committed with public/assets/replay/manifest.json. */",
  "",
  'import type { SceneAssets } from "./index.ts";',
  "",
  `export const REPLAY_ASSETS: SceneAssets = ${JSON.stringify(result.assets, null, 2)};`,
  "",
].join("\n");
writeFileSync(CONTRACT, body);
for (const o of result.outcomes) console.log(`${o.beatId}: ${o.status}${o.repaired ? " (repaired)" : ""}${o.reason !== null ? ` - ${o.reason}` : ""}`);
console.log(`replay assets: ${Object.keys(result.assets).length} beats, $${result.costUsd.toFixed(3)}`);
